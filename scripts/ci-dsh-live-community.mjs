#!/usr/bin/env node
// Community Live Shadow (30 cases) on the pinned DSH ACP host, behind an
// independent non-executing boundary. Same host, probe and redaction as
// scripts/ci-dsh-live.mjs; the cases come from the supplied community casebook.
//
//   node scripts/ci-dsh-live-community.mjs --dsh <dsh bin> --root <empty dir> --evidence <dir> [--classifier live|mock]
//     [--repeat N] [--controls] [--reasoning-effort <effort>]
//
// --classifier live (default) routes the plugin's classifier to OpenCode Go
// (needs OPENCODE_GO_API_KEY). --classifier mock keeps the scripted local
// endpoint and answers every classification with low/approve, so the boundary
// and the host chain can be proven on pull requests without any secret.
//
// Non-executing boundary. A generated CI-only plugin (dsh-ci-inert-exec)
// provides the `shell` service in place of the disabled bash-sandbox executor
// and replaces the file service's only two mutators (writeText, editText).
// Every call into them is recorded (hash only) and refused before any
// process spawn or file write. Before any case runs, five controls prove the
// boundary: approved and plain bash and write calls, and a plain edit, reach
// the inert seams and leave the filesystem unchanged. If any control fails,
// no case is started. Shadow mode and client rejection stay on as additional
// layers, not as the proof.
//
// --repeat N (1-20, default 1) runs the whole case list N times in fresh
// sessions, so the summary's `stability` section can show how often the same
// request flips between verdicts. --controls appends the paired control cases
// in test/fixtures/approval-reliability-controls-2026-10-13.json (see
// docs/RELIABILITY.md). Neither changes the plugin config, labels or gates.
// --reasoning-effort (live only) sets the plugin's reasoningEffort for the
// classifier call, e.g. low; omitted keeps the provider default.
//
// --evidence receives only community-live-summary.json: ids, labels,
// decisions, reason codes, latencies, header checks and counters. No
// command text, tool arguments, user text or model messages are written there.

